"""
Batch runner for the redshift truncation scan.

Generates Cobaya YAML configs for a grid of:
    z_cut values: [0.00, 0.02, 0.05, 0.08, 0.10, 0.12, 0.15, 0.20]
    datasets:     [PantheonPlus, DESY5]
    data combos:  [SN only, SN + BAO]  (add CMB if Planck data installed)

Usage:
    python run_scan.py --dry-run          # Generate configs only, don't run
    python run_scan.py --run              # Run all chains
    python run_scan.py --run --dataset pantheonplus  # Run only one dataset
    python run_scan.py --run --zcut 0.10  # Run only one z_cut
"""

import os
import sys
import subprocess
import argparse
from pathlib import Path

# ── Configuration ────────────────────────────────────────────────────
BASE_DIR = Path(__file__).parent
CONFIG_DIR = BASE_DIR / "configs"
CHAIN_DIR = BASE_DIR / "chains"
PYTHON = r"C:\Users\ztmat\AppData\Local\Python\bin\python3.exe"

Z_CUTS = [0.00, 0.02, 0.05, 0.08, 0.10, 0.12, 0.15, 0.20]

# Model: "wcdm" or "cpl"
MODEL = "cpl"

DATASETS = {
    "pantheonplus": {
        "likelihood_name": "truncation_sn.TruncatedPantheonPlus",
        "label": "pp",
    },
    "desy5": {
        "likelihood_name": "truncation_sn.TruncatedDESy5",
        "label": "dy5",
    },
}

# Which additional likelihoods to include.
# Set to False/True depending on what data you have installed.
DATA_COMBOS = {
    "sn_only": {
        "extra_likelihoods": {},
        "label_suffix": "",
        "ombh2_prior": {"min": 0.005, "max": 0.04},
        "ombh2_ref": 0.0224,
    },
    "sn_bao": {
        "extra_likelihoods": {"bao.desi_dr2": None},
        "label_suffix": "_bao",
        "ombh2_prior": {"min": 0.005, "max": 0.04},
        "ombh2_ref": 0.0224,
    },
    "sn_bao_cmb": {
        "extra_likelihoods": {"bao.desi_dr2": None},
        "label_suffix": "_bao_cmb",
        # Planck 2018 Gaussian prior on omega_b
        "ombh2_prior": {"dist": "norm", "loc": 0.02237, "scale": 0.00015},
        "ombh2_ref": 0.02237,
    },
}

YAML_TEMPLATE = """# Auto-generated config: {dataset} | zcut={zcut} | {combo_name}
# Generated by run_scan.py

theory:
  camb:
    extra_args:
      lens_potential_accuracy: 1
      dark_energy_model: ppf

likelihood:
  {likelihood_name}:
    zcut: {zcut}
{extra_likelihoods_block}

params:
  ombh2:
    prior: {ombh2_prior}
    ref: {ombh2_ref}
    proposal: 0.0001
  omch2:
    prior: {{min: 0.01, max: 0.99}}
    ref: 0.12
    proposal: 0.001
  H0:
    prior: {{min: 20, max: 100}}
    ref: 67.4
    proposal: 0.5
  tau:
    prior:
      dist: norm
      loc: 0.054
      scale: 0.007
    ref: 0.054
    proposal: 0.003
  As:
    prior: {{min: 2, max: 4}}
    ref: 3.05
    proposal: 0.01
  ns:
    prior: {{min: 0.8, max: 1.2}}
    ref: 0.965
    proposal: 0.003
  w:
    prior: {{min: -3, max: 1}}
    ref: -1.0
    proposal: 0.05
    latex: w_0
{extra_params_block}

sampler:
  mcmc:
    drag: true
    max_tries: 1000
    Rminus1_stop: 0.01
    Rminus1_cl_stop: 0.03
    max_samples: 10000

output: {output_dir}
"""


def _get_extra_params():
    """Return extra parameter YAML block based on model."""
    if MODEL == "cpl":
        return """  wa:
    prior: {min: -5, max: 5}
    ref: 0.0
    proposal: 0.2
    latex: w_a"""
    return ""


def _get_model_label():
    """Return model label for output naming."""
    if MODEL == "cpl":
        return "cpl_"
    return ""


def generate_configs(datasets=None, zcuts=None, combos=None):
    """Generate all YAML config files. Returns list of (config_path, output_dir)."""
    if datasets is None:
        datasets = list(DATASETS.keys())
    if zcuts is None:
        zcuts = Z_CUTS
    if combos is None:
        combos = list(DATA_COMBOS.keys())

    os.makedirs(CONFIG_DIR, exist_ok=True)
    configs = []

    for dataset_key in datasets:
        ds = DATASETS[dataset_key]
        for zcut in zcuts:
            for combo_key in combos:
                combo = DATA_COMBOS[combo_key]

                # Build the extra likelihoods YAML block
                extra_lines = []
                for like_name, like_config in combo["extra_likelihoods"].items():
                    if like_config is None:
                        extra_lines.append(f"  {like_name}:")
                    else:
                        extra_lines.append(f"  {like_name}:")
                        for k, v in like_config.items():
                            extra_lines.append(f"    {k}: {v}")

                extra_block = "\n".join(extra_lines)

                # Output directory
                zcut_str = f"{zcut:.2f}".replace(".", "p")
                output_dir = (
                    f"chains/{_get_model_label()}{ds['label']}_z{zcut_str}{combo['label_suffix']}"
                )

                # Config filename
                config_name = (
                    f"{_get_model_label()}{ds['label']}_z{zcut_str}{combo['label_suffix']}.yaml"
                )
                config_path = CONFIG_DIR / config_name

                # Format the ombh2 prior dict as YAML
                import json
                ombh2_prior_str = json.dumps(combo["ombh2_prior"]).replace('"', '')
                # Handle norm case: {"dist": "norm", "loc": 0.02237, "scale": 0.00015}
                # -> {dist: norm, loc: 0.02237, scale: 0.00015}

                content = YAML_TEMPLATE.format(
                    dataset=dataset_key,
                    zcut=zcut,
                    combo_name=combo_key,
                    likelihood_name=ds["likelihood_name"],
                    extra_likelihoods_block=extra_block,
                    extra_params_block=_get_extra_params(),
                    output_dir=output_dir,
                    ombh2_prior=ombh2_prior_str,
                    ombh2_ref=combo["ombh2_ref"],
                )

                with open(config_path, "w") as f:
                    f.write(content)

                configs.append((config_path, output_dir))

    return configs


def run_single(config_path):
    """Run a single Cobaya chain."""
    print(f"\n{'='*60}")
    print(f"Running: {config_path.name}")
    print(f"{'='*60}")

    env = os.environ.copy()
    env["PYTHONPATH"] = str(BASE_DIR) + (
        os.pathsep + env.get("PYTHONPATH", "")
    )

    cmd = [
        PYTHON, "-m", "cobaya.run",
        str(config_path),
    ]

    result = subprocess.run(cmd, cwd=str(BASE_DIR), env=env)
    if result.returncode != 0:
        print(f"ERROR: Chain failed for {config_path.name}")
        return False
    return True


def main():
    parser = argparse.ArgumentParser(
        description="Batch run redshift truncation scan"
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Generate config files only, do not run chains"
    )
    parser.add_argument(
        "--run", action="store_true",
        help="Run the MCMC chains"
    )
    parser.add_argument(
        "--dataset", type=str, default=None,
        help="Run only a specific dataset (pantheonplus or desy5)"
    )
    parser.add_argument(
        "--zcut", type=float, default=None,
        help="Run only a specific z_cut value"
    )
    parser.add_argument(
        "--combo", type=str, default=None,
        help="Run only a specific data combination (sn_only, sn_bao, sn_cmb)"
    )
    args = parser.parse_args()

    datasets = [args.dataset] if args.dataset else None
    zcuts = [args.zcut] if args.zcut else None
    combos = [args.combo] if args.combo else None

    # Generate configs
    configs = generate_configs(datasets=datasets, zcuts=zcuts, combos=combos)

    print(f"\nGenerated {len(configs)} configuration files in {CONFIG_DIR}/")
    for config_path, output_dir in configs:
        print(f"  {config_path.name} → {output_dir}")

    if args.dry_run or not args.run:
        print("\nDry run complete. Use --run to execute the chains.")
        return

    # Run chains
    print(f"\nStarting {len(configs)} MCMC chains...")
    success = 0
    failed = 0
    for config_path, output_dir in configs:
        if run_single(config_path):
            success += 1
        else:
            failed += 1

    print(f"\n{'='*60}")
    print(f"Done. Success: {success}, Failed: {failed}")
    print(f"Chains saved in {CHAIN_DIR}/")
    print(f"{'='*60}")


if __name__ == "__main__":
    main()
